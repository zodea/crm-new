it('可信身份变化、只读和同键异文均不增加序号，已出具可只读输出', async () => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  await f.initialize()
  const command = numberingCommand(await f.read(), 'identity-issue', { kind: 'issue' })
  await expect(f.service.executeNumbering({ ...command, actorId: 'other' })).rejects.toMatchObject({ problem: { code: 'forbidden' } })
  const result = await f.service.executeNumbering(command)
  await expect(f.service.executeNumbering({ ...command, sourceVersion: 'different' })).rejects.toMatchObject({ problem: { code: 'conflict' } })
  f.setSession({ workspaceId: 'work', actorId: 'actor', capabilities: ['payroll:read'] })
  const read = await f.read()
  expect(read.eligibility).toMatchObject({ canIssue: false, canDownload: true })
  expect(read.issue).toEqual(result.issue)
  await expect(f.service.executeNumbering(command)).rejects.toMatchObject({ problem: { code: 'forbidden' } })
  expect(read.settings?.nextNumber).toBe(129)
  f.setSession({ workspaceId: 'work', actorId: 'actor', capabilities: [] })
  await expect(f.read()).rejects.toMatchObject({ problem: { code: 'forbidden' } })
})
it('异步写入期间操作者撤权时整单回滚，恢复权限后原键安全出具', async () => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  await f.initialize()
  const command = numberingCommand(await f.read(), 'revoke-during-number', { kind: 'issue' })
  let reads = 0
  f.setIdentityHook(() => {
    if (++reads === 2)
      f.setSession({ workspaceId: 'work', actorId: 'actor', capabilities: ['payroll:read'] })
  })
  await expect(f.service.executeNumbering(command)).rejects.toMatchObject({ problem: { code: 'forbidden', commandOutcome: 'not-applied' } })
  f.setIdentityHook(null)
  f.setSession({ workspaceId: 'work', actorId: 'actor', capabilities: ['payroll:read', 'payroll:write'] })
  expect((await f.read()).settings?.nextNumber).toBe(128)
  expect(await f.db.select('SELECT * FROM payroll_official_issues')).toHaveLength(0)
  expect((await f.service.executeNumbering(command)).issue?.number).toBe('128')
})
it('读写codec拒绝错误原单、项目、权限和越界起点', async () => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  const read = await f.read()
  expect(decodePayrollNumberingRead(encodePayrollNumberingRead(read), { origin: 'real' }, f.input)).toEqual(read)
  for (const value of [0, -1, 1.2, Number.MAX_SAFE_INTEGER]) expect(() => parsePayrollNumberingCommand(numberingCommand(read, 'invalid-init', { kind: 'initialize', nextNumber: value, evidenceNote: '依据' }))).toThrow()
  for (const changed of [{ ...read, input: { ...f.input, projectId: 'other-project' } }, { ...read, context: { ...read.context, capabilities: [] } }, { ...read, document: { ...read.document, id: 'unrelated' } }])
    expect(() => decodePayrollNumberingRead(changed, { origin: 'real' }, f.input)).toThrow()
})
