import { afterEach, expect, it } from 'vitest'
import { decodePayrollNumberingRead, encodePayrollNumberingRead, parsePayrollNumberingCommand } from '../../app/lib/payroll/central-numbering-codec'
import { createCheckedPayrollC2, createPayrollC2ServiceFixture } from '../helpers/payroll-c2-service-fixture'
import { createPayrollNumberingFixture, numberingCommand } from '../helpers/payroll-numbering-fixture'

const closers: Array<() => Promise<void>> = []
afterEach(async () => {
  for (const close of closers.splice(0)) await close()
})
it('双窗相同原单不同提交只有一次占号，另窗先重读后仍返回原号', async () => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  await f.initialize()
  const old = await f.read()
  const results = await Promise.allSettled(['window-1', 'window-2'].map(id => f.service.executeNumbering(numberingCommand(old, id, { kind: 'issue' }))))
  expect(results.filter(row => row.status === 'fulfilled')).toHaveLength(1)
  expect(results.filter(row => row.status === 'rejected')).toMatchObject([{ reason: { problem: { code: 'stale-source', commandOutcome: 'not-applied' } } }])
  expect((await f.issue('after-refresh')).issue?.number).toBe('128')
  expect((await f.read()).settings?.nextNumber).toBe(129)
  expect(await f.db.select('SELECT * FROM payroll_official_issues')).toHaveLength(1)
})
it('写入回执前失败回滚序列和原号，原键可以安全重试', async () => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  await f.initialize()
  const command = numberingCommand(await f.read(), 'will-fail-before-receipt', { kind: 'issue' })
  await f.db.execute('CREATE TRIGGER fail_numbering_receipt BEFORE INSERT ON payroll_command_receipts WHEN NEW.action=\'numbering-issue\' BEGIN SELECT RAISE(ABORT,\'simulated receipt failure\'); END')
  await expect(f.service.executeNumbering(command)).rejects.toThrow('simulated receipt failure')
  expect(await f.db.select('SELECT * FROM payroll_official_issues')).toHaveLength(0)
  expect((await f.read()).settings?.nextNumber).toBe(128)
  await f.db.execute('DROP TRIGGER fail_numbering_receipt')
  expect((await f.service.executeNumbering(command)).issue?.number).toBe('128')
})
it('同项目跨格式和月份并发出具共用一个序列，陈旧窗重读后得到下一号', async () => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  const matrix = await f.service.attendanceMatrix({ origin: 'real' }, { projectId: 'p', crewId: 'crew', month: '2026-09' })
  await f.service.executeAttendance(f.attendanceCommand(matrix, { workerId: 'w', crewId: 'crew', workDate: '2026-09-01', hours: 8, overtimeHours: 0, workContent: '次月施工', note: '' }))
  const draft = { projectId: 'p', crewId: 'crew', month: '2026-09', leaderWorkerId: 'w', memberWorkerIds: ['w'], note: '' }
  const saved = await f.service.executeC1(f.command(await f.form(draft, 'numbered-c1'), { kind: 'save-c1-draft', draft }))
  const c1 = () => f.service.c1Form({ origin: 'real' }, { statementId: saved.statementId! })
  await f.service.executeC1(f.command(await c1(), { kind: 'check-c1' }))
  await f.service.executeC1(f.command(await c1(), { kind: 'release-c1', release: { actualAmount: 481, allocations: [{ workerId: 'w', amount: 481 }] } }))
  await f.initialize()
  const input = { projectId: 'p', statementId: saved.statementId! }
  const second = () => f.service.numbering({ origin: 'real' }, input)
  const commands = [numberingCommand(await f.read(), 'parallel-c2', { kind: 'issue' }), numberingCommand(await second(), 'parallel-c1', { kind: 'issue' })]
  const results = await Promise.allSettled(commands.map(command => f.service.executeNumbering(command)))
  expect(results.filter(row => row.status === 'fulfilled')).toHaveLength(1)
  expect(results.filter(row => row.status === 'rejected')).toHaveLength(1)
  await f.service.executeNumbering(numberingCommand(await second(), 'refreshed-c1', { kind: 'issue' }))
  expect((await f.read()).issue?.number).toBe('128')
  expect((await second()).issue?.number).toBe('129')
  expect((await second()).settings?.nextNumber).toBe(130)
  expect((await c1()).status).toBe('released')
})
it.each(['sequence', 'issue-hash', 'receipt-project', 'receipt-result', 'receipt-missing'] as const)('损坏 %s 明确阻断输出与重新占号', async (kind) => {
  const f = await createPayrollNumberingFixture()
  closers.push(f.close)
  await f.initialize()
  await f.issue()
  if (kind === 'sequence')
    await f.db.execute('UPDATE payroll_numbering_settings SET next_number=130')
  if (kind === 'issue-hash')
    await f.db.execute('UPDATE payroll_official_issues SET document_hash=?', ['f'.repeat(64)])
  if (kind === 'receipt-project')
    await f.db.execute('UPDATE payroll_command_receipts SET project_id=\'other-project\' WHERE action=\'numbering-issue\'')
  if (kind === 'receipt-result')
    await f.db.execute('UPDATE payroll_command_receipts SET result_json=\'{}\' WHERE action=\'numbering-issue\'')
  if (kind === 'receipt-missing')
    await f.db.execute('DELETE FROM payroll_command_receipts WHERE action=\'numbering-issue\'')
  await expect(f.read()).rejects.toMatchObject({ problem: { code: 'unavailable' } })
  expect(await f.db.select('SELECT * FROM payroll_official_issues')).toHaveLength(1)
})
