async function frozenOutput(page: Page, info: TestInfo) {
  await page.addInitScript(() => Object.defineProperty(window, 'showDirectoryPicker', { configurable: true, value: undefined }))
  await page.reload()
  const downloading = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载冻结工资表', exact: true }).click()
  const file = await downloading
  const path = info.outputPath('hollow-550-frozen.xlsx')
  await file.saveAs(path)
  const book = XLSX.read(await readFile(path))
  expect(XLSX.utils.sheet_to_json(book.Sheets.空鼓扣款汇总!)).toEqual([expect.objectContaining({ 本次请款合计: 1000, 本单空鼓扣款: 450, 扣款后核算应发: 550 })])
  expect(XLSX.utils.sheet_to_json(book.Sheets.空鼓采用来源!)).toContainEqual(expect.objectContaining({ 检查总处数: 19, 已整改处数: 4, 当时未整改处数: 15, 本单采用处数: 15, 采用单处金额: 30, 本单扣款金额: 450 }))
  await page.getByRole('button', { name: '打印冻结工资表', exact: true }).click()
  await page.emulateMedia({ media: 'print' })
  const pdf = await page.pdf({ path: info.outputPath('hollow-550-frozen.pdf'), printBackground: true, preferCSSPageSize: true })
  const { getDocument } = await import('pdfjs-dist/legacy/build/pdf.mjs')
  const printed = await getDocument({ data: new Uint8Array(pdf) }).promise
  const texts: string[] = []
  for (let number = 1; number <= printed.numPages; number++) {
    const content = await (await printed.getPage(number)).getTextContent()
    texts.push(content.items.flatMap(item => 'str' in item ? [item.str] : []).join(''))
  }
  expect(texts.join('')).toContain('19 / 4 / 15')
  expect(texts.join('')).toContain('550.00')
  expect(texts.join('')).toContain('450.00')
  await writeFile(info.outputPath('hollow-print-verification.json'), JSON.stringify({ pages: printed.numPages, texts }, null, 2))
  await printed.destroy()
  await page.emulateMedia({ media: 'screen' })
}

