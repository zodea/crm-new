import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'
import { payrollFeesWorkspace } from './helpers/payroll-fees-workspace'

test('A 工资逐分项比例、费用覆盖、少发与上月继承的隔离整页旅程', async ({ page }, info) => {
  test.setTimeout(240_000)
  const workspace = await payrollFeesWorkspace(page, info)
  const scope = await workspace.project('fee-ordinary')
  await page.goto(scope.configPath())
  await page.getByRole('button', { name: '新增费用', exact: true }).click()
  const fee = page.getByRole('article', { name: '费用配置行', exact: true }).last()
  await fee.getByLabel('费用名称', { exact: true }).fill('墙面测试补贴')
  await fee.getByLabel('费用类别', { exact: true }).selectOption('subsidy')
  await fee.getByLabel('启用此费用', { exact: true }).check()
  await fee.getByLabel('费用单价', { exact: true }).fill('1.3')
  await fee.getByLabel('费用单位', { exact: true }).fill('㎡')
  await fee.getByRole('checkbox', { name: /^墙砖 ·/ }).check()
  await fee.getByLabel('费用完成量范围', { exact: true }).selectOption('project')
  await page.getByRole('button', { name: '保存费用配置', exact: true }).click()
  await expect(fee).toHaveCount(0)
  const target = (month: string) => `/subcontract/payroll/new?${new URLSearchParams({ origin: 'real', project: scope.projectId, crew: scope.crewId, month, draftKey: randomUUID() })}`
  await page.goto(target('2026-07'))
  await page.getByLabel('请款负责人', { exact: true }).selectOption(scope.leaderWorkerId)
  await page.getByLabel('本次支付比例', { exact: true }).fill('80')
  await page.getByRole('button', { name: '核对完成量与单价', exact: true }).click()
  const ratios = page.getByRole('region', { name: '工程量分项支付比例', exact: true })
  const wall = ratios.getByRole('spinbutton', { name: / · 墙砖支付比例$/ })
  await expect(wall).toBeEnabled()
  await expect(wall).toHaveValue('')
  await expect(page.getByRole('button', { name: '保存工资草稿', exact: true })).toBeDisabled()
  const entries = ratios.locator('input[aria-label$="支付比例"]')
  for (let index = 0; index < await entries.count(); index++) {
    const entry = entries.nth(index)
    const label = await entry.getAttribute('aria-label')
    await entry.fill(label?.endsWith(' · 墙砖支付比例') ? '50' : '20')
    const refreshed = page.waitForResponse(response => response.url().endsWith('/api/read/payroll/a-form') && response.request().method() === 'POST')
    await entry.blur()
    expect((await refreshed).ok()).toBe(true)
  }
  const feeRatio = ratios.getByLabel('墙面测试补贴单独比例', { exact: true })
  await feeRatio.fill('20')
  const refreshed = page.waitForResponse(response => response.url().endsWith('/api/read/payroll/a-form') && response.request().method() === 'POST')
  await feeRatio.blur()
  expect((await refreshed).ok()).toBe(true)
  for (const width of [390, 768, 1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    await expect.poll(() => page.locator('.shell-workspace').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
  }
  await expect(page.getByRole('button', { name: '保存工资草稿', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '保存工资草稿', exact: true }).click()
  await expect(page).toHaveURL(url => /^\/subcontract\/payroll\/[^/]+$/.test(url.pathname) && !url.pathname.endsWith('new'))
  const statementId = decodeURIComponent(new URL(page.url()).pathname.split('/').at(-1)!)
  let read = await workspace.repository.aForm(workspace.query, { statementId })
  expect(read.totals.cumulativeAmount.value).toBe(1826)
  await page.getByRole('button', { name: '重新核对工资', exact: true }).click()
  await page.getByRole('button', { name: '确认实际发放', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('实际发放总额', { exact: true }).fill('100')
  await dialog.getByLabel('同人普通工资与管理人收款金额', { exact: true }).fill('100')
  await dialog.getByRole('button', { name: '确认实际发放', exact: true }).click()
  await expect(page.getByRole('button', { name: '下载冻结工资表', exact: true })).toBeVisible()
  read = await workspace.repository.aForm(workspace.query, { statementId })
  expect(read.draft.ratioPlan?.itemRatios.find(row => row.itemId === scope.items['墙砖'])?.ratio).toBe(0.5)
  await page.goto(target('2026-08'))
  await page.getByLabel('请款负责人', { exact: true }).selectOption(scope.leaderWorkerId)
  await page.getByRole('button', { name: '核对完成量与单价', exact: true }).click()
  const next = page.getByRole('region', { name: '工程量分项支付比例', exact: true })
  await expect(next.getByRole('spinbutton', { name: / · 墙砖支付比例$/ })).toHaveValue('50')
  await expect(next.getByLabel('墙面测试补贴单独比例', { exact: true })).toHaveValue('20')
  await page.getByLabel('工资档位', { exact: true }).selectOption('retention')
  await expect(next.getByRole('spinbutton', { name: / · 墙砖支付比例$/ })).toHaveValue('100')
  await expect(next.getByRole('spinbutton', { name: / · 墙砖支付比例$/ })).toBeDisabled()
})
