function urlIdentity(value: string) {
  const url = new URL(value)
  return { pathname: url.pathname, searchParams: [...url.searchParams].sort(([ak, av], [bk, bv]) => ak.localeCompare(bk) || av.localeCompare(bv)), hash: url.hash }
}
async function expectSameLocation(page: Page, expected: string) {
  await expect.poll(() => urlIdentity(page.url())).toEqual(urlIdentity(expected))
}
async function capture(page: Page, info: TestInfo, name: string, selector?: string, horizontal = false) {
  await expect(page.locator('[data-sonner-toast]:visible')).toHaveCount(0, { timeout: 15000 })
  for (const width of [390, 768, 1024, 1280, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    if (selector)
      await page.locator(selector).first().evaluate(node => node.scrollIntoView({ block: 'center' }))
    if (horizontal && selector)
      await page.locator(selector).first().evaluate(node => node.scrollLeft = node.scrollWidth - node.clientWidth)
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    await expect.poll(() => page.locator('.shell-workspace').evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`${name}-${width}.png`), fullPage: true, animations: 'disabled' })
  }
  await page.setViewportSize({ width: 1440, height: 960 })
}

async function saveRecord(page: Page, path: string, worker: string, date: string, units: string, confirmed: boolean) {
  await page.goto(path)
  await page.getByRole('link', { name: '新增签工记录', exact: true }).click()
  await expect(page.getByRole('heading', { name: '新增签工记录', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '签工用工人', exact: true }).fill(worker)
  await page.getByRole('option', { name: worker, exact: true }).click()
  await page.getByLabel('用工日期', { exact: true }).fill(date)
  await page.getByLabel('开始时间', { exact: true }).fill('08:00')
  await page.getByLabel('结束时间', { exact: true }).fill(units === '1' ? '17:00' : '12:00')
  await page.getByLabel('用工数', { exact: true }).selectOption(units)
  await page.getByLabel('施工内容', { exact: true }).fill(`${worker} ${date} 原施工内容`)
  if (confirmed) {
    await page.getByLabel('证明人', { exact: true }).fill('现场证明甲')
    await page.getByLabel('确认日期', { exact: true }).fill(date)
  }
  const saving = page.waitForResponse(response => response.url().endsWith('/api/commands/payroll-daywork') && response.request().method() === 'POST')
  await page.getByRole('button', { name: confirmed ? '保存并确认' : '保存待确认', exact: true }).click()
  const saved = await saving
  expect(saved.ok(), await saved.text()).toBe(true)
  const result = await saved.json()
  expect(result.status).toBe(confirmed ? 'confirmed' : 'draft')
  await expect(page.getByRole('heading', { name: '零星签工', exact: true })).toBeVisible()
  return result.recordId as string
}

