    await page.getByRole('button', { name: '返回来源', exact: true }).click()
    await expect(page).toHaveURL(/page=2/)
    await expect(page.getByRole('link', { name: '合成事实结算 11', exact: true })).toBeFocused()
    await page.getByRole('link', { name: '合成事实结算 11', exact: true }).click()
    await expect(page.getByRole('heading', { name: '合成事实结算 11', exact: true })).toBeVisible()
    const detailUrl = page.url()
    const mismatchUrl = new URL(detailUrl)
    mismatchUrl.searchParams.set('contractId', 'foreign')
    await page.goto(mismatchUrl.toString())
    await expect(page.getByText('结算来源或合同关系不匹配', { exact: true })).toBeVisible()
    await page.goto(detailUrl)
    await page.getByRole('button', { name: '编辑结算' }).click()
    await page.getByLabel('结算名称 *').fill('重试后的结算')
    const commands: string[] = []
    await page.route('**/api/commands/other-settlements', async (route) => {
      commands.push(route.request().postDataJSON().commandId)
      const response = await route.fetch()
      if (commands.length === 1)
        await route.abort('failed')
      else
        await route.fulfill({ response })
    })
    const save = page.getByRole('group', { name: '表单操作' }).getByRole('button', { name: '保存', exact: true })
    await save.click()
    await expect(page.getByRole('alert').filter({ hasText: '当前输入已保留' })).toBeVisible()
