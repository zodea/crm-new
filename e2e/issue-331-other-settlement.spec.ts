    await expect(page.getByRole('heading', { name: '重试后的结算' })).toBeVisible()
    expect(commands).toHaveLength(2)
    expect(commands[0]).toBe(commands[1])
    await page.unroute('**/api/commands/other-settlements')
    await page.getByRole('button', { name: '编辑结算' }).click()
    const current = (await (await page.request.get('/api/read/other-settlements/synthetic-settlement-10')).json()).settlement
