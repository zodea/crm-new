test('无区域正式项目可往返区域与模板，保留项目身份及建组草稿', async ({ page }) => {
  const fixture = await installScheduleProductionFixture(page)
  const session = await (await page.request.get('/api/read/business-session')).json()
  const created = await page.request.post('/api/commands/projects', { data: { ...session, commandId: randomUUID(), requiredCapability: 'project:write', baseVersion: null, action: 'draft', draft: { name: '正式无区域项目', manager: '合成经办人', status: '筹备中' }, attachments: {} } })
  expect(created.ok(), await created.text()).toBe(true)
  const id = (await created.json()).id
  await page.goto(`/schedule/new?project=${id}&origin=real`)
  await page.getByRole('radio', { name: /内部暂估/ }).check()
  await page.getByLabel('分组名称', { exact: true }).fill('返回后保留的暂估分组')
  await expect(page.getByText(/当前项目尚未维护可用楼栋/)).toBeVisible()
  await page.getByRole('link', { name: '配置楼栋、楼层与户', exact: true }).click()
  await expect(page).toHaveURL(url => url.pathname === '/subcontract/quantity/region' && url.searchParams.get('project') === id && url.searchParams.get('return') === 'schedule')
  await page.getByRole('link', { name: '新建户型模板', exact: true }).click()
  await expect(page).toHaveURL(url => url.pathname === '/subcontract/quantity/template' && url.searchParams.get('project') === id && url.searchParams.get('return') === 'region')
  await page.getByRole('button', { name: '返回区域配置', exact: true }).click()
  await page.getByRole('button', { name: '返回新建排程', exact: true }).click()
  await expect(page.getByLabel('分组名称', { exact: true })).toHaveValue('返回后保留的暂估分组')
  await expect(page.getByRole('radio', { name: /内部暂估/ })).toBeChecked()
  expect(fixture.projectId).not.toBe(id)
})
