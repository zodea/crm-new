test('依赖弹窗只提供同组更早工序，Escape 和取消保持原依赖', async ({ page }) => {
  const fixture = await installScheduleProductionFixture(page)
  const before = (await fixture.readSchedule()).snapshot.dependencies
  await page.goto(fixture.scheduleUrl)
  await page.getByRole('button', { name: '卫生间回填及防水', exact: true }).click()
  const detail = page.getByRole('dialog', { name: '工序详情 · 卫生间回填及防水', exact: true })
  await detail.getByRole('button', { name: '修改依赖', exact: true }).click()
  await expect(detail).toBeHidden()
  const dependency = page.getByRole('dialog', { name: '依赖设置 · 卫生间回填及防水', exact: true })
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await expect(dependency.getByText('楼栋分组：正式一栋组', { exact: true })).toBeVisible()
  await expect(dependency.getByText('完成 → 开始（FS）', { exact: true })).toBeVisible()
  expect((await dependency.boundingBox())!.width).toBeLessThanOrEqual(440)
  await dependency.getByRole('combobox', { name: '前置工序', exact: true }).click()
  await expect(page.getByRole('option')).toHaveText(['放线及新建墙体 · 2026-08-01—2026-08-02', '给排水安装 · 2026-08-03—2026-08-05'])
  await expect(page.getByRole('option', { name: /^开荒保洁/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await dependency.getByRole('spinbutton', { name: 'Lag 天数', exact: true }).fill('17')
  await page.keyboard.press('Escape')
  const discard = page.getByRole('dialog', { name: '放弃依赖设置修改？', exact: true })
  await discard.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dependency).toBeVisible()
  await dependency.getByRole('button', { name: '取消', exact: true }).click()
  await discard.getByRole('button', { name: '放弃修改', exact: true }).click()
  await expect(detail).toBeVisible()
  expect((await fixture.readSchedule()).snapshot.dependencies).toEqual(before)
  await expectNoPageOverflow(page, '排程依赖取消')
})

test('甘特拖动冲突取消不写入，确认只置灰冲突依赖，右缘键盘改期回读', async ({ page }) => {
  const fixture = await installScheduleProductionFixture(page)
  await page.goto(fixture.scheduleUrl)
  const plumbing = page.getByRole('button', { name: '移动工序：给排水安装', exact: true })
  await plumbing.scrollIntoViewIfNeeded()
  const axis = await plumbing.locator('..').boundingBox()
  expect(axis).not.toBeNull()
  const moveEarlier = async () => {
    const box = await plumbing.boundingBox()
    expect(box).not.toBeNull()
    const start = { x: box!.x + box!.width / 2, y: box!.y + box!.height / 2 }
    await page.mouse.move(start.x, start.y)
    await page.mouse.down()
    await page.mouse.move(start.x - axis!.width / 31, start.y, { steps: 5 })
    await page.mouse.up()
  }
  await moveEarlier()
  const conflict = page.getByRole('dialog', { name: /本次调期会冲突/ })
  await conflict.getByRole('button', { name: '取消', exact: true }).click()
  let snapshot = (await fixture.readSchedule()).snapshot
  expect(snapshot.groups[0]!.tasks.find(task => task.name === '给排水安装')!.plannedStart).toBe('2026-08-03')
  expect(snapshot.dependencies).toHaveLength(3)
  expect(snapshot.disabledDependencies).toHaveLength(0)
  await moveEarlier()
  await conflict.getByRole('button', { name: '调期并置灰冲突', exact: true }).click()
  await expect.poll(async () => (await fixture.readSchedule()).snapshot.groups[0]!.tasks.find(task => task.name === '给排水安装')!.plannedStart).toBe('2026-08-02')
  snapshot = (await fixture.readSchedule()).snapshot
  expect(snapshot.dependencies).toHaveLength(2)
  expect(snapshot.disabledDependencies).toHaveLength(1)
  const resized = page.waitForResponse(response => new URL(response.url()).pathname === '/api/commands/schedule' && response.request().method() === 'POST')
  await page.getByRole('button', { name: '调整工期：开荒保洁', exact: true }).press('ArrowRight')
  const resizeReceipt = await resized
  expect(resizeReceipt.ok(), await resizeReceipt.text()).toBe(true)
  await expect.poll(async () => (await fixture.readSchedule()).snapshot.groups[0]!.tasks.find(task => task.name === '开荒保洁')!.plannedFinish).toBe('2026-08-12')
  await expect(page.getByRole('button', { name: '调整工期：开荒保洁', exact: true })).toBeEnabled()
  await page.reload()
  await expect(page.locator('.dependency-path.is-disabled')).toHaveCount(1)
  await expectNoPageOverflow(page, '甘特调期')
})

